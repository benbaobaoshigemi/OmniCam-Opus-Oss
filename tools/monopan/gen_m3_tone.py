"""Write app/src/main/cpp/monopan_tone.h: the MonoPan50 (Xiaomi M3) tone as 1D tables.

M3 develops linear light (18 % grey = 0.18 here) with its Gamma1774 leaf (257 nodes over 0..1, 10-bit
codes; DRC 1 is the leaf with no range compression) and writes a display code. The leaf is stored in whole
codes, a staircase that the HDR rendition stretches into contours, so the table smooths it (Savitzky-Golay,
11 nodes, order 2: within about a code of the stored leaf). The master pipeline's
neutral curve (tools/softlight/gen_curve.py, soft_light_curve.h) turns the LMT output back into scene
light; this table turns the M3 display code into the LMT output whose HDRTransform master luma
(x9u_master_tonecurve) is that code, so the HDR rendition of a grey follows the M3 tone.

Usage: gen_m3_tone.py
"""
import json
from pathlib import Path

import numpy as np
from scipy.signal import savgol_filter

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "tools/monopan/data/m3_gamma1774.json"
GRAIN = ROOT / "tools/monopan/data/grain_tone.json"
TONE = ROOT / "tools/mastercolor/data/x9u_master_tonecurve.npy"
OUT = ROOT / "app/src/main/cpp/monopan_tone.h"
N = 1024


def table(name, values, size):
    body = ",\n".join("    " + ", ".join(f"{v:.6e}f" for v in values[i:i + 8]) for i in range(0, len(values), 8))
    return [f"constexpr float {name}[{size}] = {{", body, "};", ""]


def main():
    leaves = json.loads(DATA.read_text(encoding="utf-8"))
    leaf = next(e for e in leaves if e["drc"][0] <= 1.0 <= e["drc"][1])
    gamma = savgol_filter(np.asarray(leaf["curve"], dtype=np.float64), 11, 2, mode="interp") / 1023.0
    assert gamma.size == 257 and np.all(np.diff(gamma) >= 0)

    tone = np.maximum.accumulate(np.load(TONE).astype(np.float64))    # HLG code k/1023 -> display code
    assert tone.size == N
    display = np.arange(N) / (N - 1)
    uniq, first = np.unique(tone, return_index=True)
    hlg = np.interp(display, uniq, first / (N - 1))                  # display code -> HLG signal

    lines = [
        "// Generated by tools/monopan/gen_m3_tone.py: the MonoPan50 tone.",
        "#pragma once",
        "",
        f"constexpr int kM3GammaN = {gamma.size};",
        f"constexpr int kM3DisplayN = {N};",
        "",
        "// Linear light x 256 -> M3 display code (uniform nodes 0..256).",
    ]
    lines += table("kM3Gamma", gamma, "kM3GammaN")
    grain = json.loads(GRAIN.read_text(encoding="utf-8"))
    lines += ["// The grain's own tone shift (mean output - input, 8-bit codes, per input level 0..255): [0] MonoPan50, [1] MonoPan50 Pro.",
              "// The preview, which has no grain, applies it so that it follows the capture's tone.",
              "constexpr float kM3GrainShift[2][256] = {"]
    for key in ("direct", "gallery"):
        lines += ["    {" + ", ".join(f"{v:.3f}f" for v in grain[key]) + "},"]
    lines += ["};", ""]
    lines += ["// M3 display code (uniform 0..1) -> LMT output (HLG signal) whose master luma is that code."]
    lines += table("kM3HlgOfDisplay", hlg, "kM3DisplayN")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("wrote", OUT, "grey 0.18 ->", np.interp(0.18 * 256, np.arange(257), gamma))


if __name__ == "__main__":
    main()
