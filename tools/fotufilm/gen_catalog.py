# The finish index (FilmStyle.FINISH_IDS) of a negative film's own print: Ektacolor Edge unless the film names another.
NATIVE = {"screen": 1, "vision-2383": 5, "eterna-cp": 7}
ORDER = [i for _, ids in GROUPS for i in ids]
GROUP_OF = {i: g for g, ids in GROUPS for i in ids}
PROJECTED = {"vision-2383", "vision-2393", "eterna-cp", "exr-5386", "agfa-cp30", "eterna-cp-3521xd"}


def main():
    films = []
    for p in sorted(glob.glob(os.path.join(F.FOTU, "Sources/FotufilmCore/Stocks/*.json"))):
        d = json.load(open(p, encoding="utf-8"))
        sid = os.path.basename(p)[:-5]
        if sid in SKIP:
            continue
        s = F.Stock(sid)
        dev = Fl.Developer(s)
        pushes = [int(x) if float(x).is_integer() else round(float(x), 4) for x in Fl.supported_development_stops(s)]
        films.append(dict(id=sid, label=LABELS.get(sid) or d.get("displayName") or d["name"], native=NATIVE.get(d.get("nativePrintMedium") or "", 2),
                          positive=bool(d["isReversal"]), monochrome=bool(d["isMonochrome"]), pushes=pushes,
                          dir=bool(dev.has_inhibition), projected=(d.get("nativePrintMedium") in PROJECTED) and not d["isReversal"],
                          reflection=bool(d.get("isReflectionPrint"))))
    missing = [f["id"] for f in films if f["id"] not in ORDER]
    if missing:
        raise SystemExit("films without a group: " + ", ".join(missing))
    films.sort(key=lambda f: ORDER.index(f["id"]))
    for f in films:
        f["group"] = GROUP_OF[f["id"]]
    (ROOT / "tools/mastercolor/catalog.json").write_text(json.dumps({"films": films}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    filters = build_filter_entries()
    arr = lambda name, vals: "    static final String[] %s = {\n%s\n    };\n" % (name, ",\n".join('        "%s"' % v for v in vals))
    iarr = lambda name, vals: "    static final int[] %s = {%s};\n" % (name, ", ".join(str(v) for v in vals))
    block = ("    // <generated by tools/fotufilm/gen_catalog.py>\n"
             + arr("FILM_IDS", [f["id"] for f in films]) + "\n" + arr("FILM_LABELS", [f["label"] for f in films]) + "\n"
             + arr("FILM_POSITIVE", ["1" if f["positive"] else "0" for f in films]) + "\n"
             + arr("FILM_MONOCHROME", ["1" if f["monochrome"] else "0" for f in films]) + "\n"
             + arr("FILM_PUSH", [",".join(str(x) for x in f["pushes"]) for f in films]) + "\n"
             + arr("FILM_DIR", ["1" if f["dir"] else "0" for f in films]) + "\n"
             + arr("FILM_PROJECTED", ["1" if f["projected"] else "0" for f in films]) + "\n"
             + arr("FILM_REFLECTION", ["1" if f["reflection"] else "0" for f in films]) + "\n"
             + arr("FILM_NATIVE", [str(f["native"]) for f in films]) + "\n"
             + arr("FILM_GROUP", [f["group"] for f in films]) + "\n"
             + arr("FILTER_IDS", [f[0] for f in filters]) + "\n"
             + arr("FILTER_LABELS", [f[1] for f in filters]) + "\n"
             + arr("FILTER_GROUP", [f[2] for f in filters]) + "\n"
             + arr("FILTER_SUMMARY", [f[3] for f in filters]) + "\n"
             + iarr("FILTER_CODE", [f[4] for f in filters])
             + "    // </generated>\n")
    java = ROOT / "app/src/main/java/local/jiege/settings/FilmStyle.java"
    text = java.read_bytes().decode("utf-8")
    crlf = "\r\n" in text
    text = text.replace("\r\n", "\n")
    new = re.sub(r"    // <generated.*?// </generated>\n", lambda m: block, text, flags=re.S)
    java.write_bytes((new.replace("\n", "\r\n") if crlf else new).encode("utf-8"))
    print(len(films), "films")


