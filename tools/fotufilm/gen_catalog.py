def build_filter_entries():
    entries = [("none", "无", "无滤镜", "不加镜头前光学玻璃滤镜", -1)]
    hue_names = {"R": "红", "G": "绿", "B": "蓝", "C": "青", "M": "品红", "Y": "黄"}
    for idx, f in enumerate(Fi.catalogue()):
        if f.id.startswith("nd"):
            continue  # TTL 测光下中性灰减光片不改变成片色彩
        if f.id in FILTER_META:
            label, group, summary = FILTER_META[f.id]
        elif f.id.startswith("cc"):
            hue = f.name[-1]
            dens = f.name[2:4]
            group = "CC 补偿 (红/绿/蓝)" if hue in ("R", "G", "B") else "CC 补偿 (青/品/黄)"
            label = f.name
            summary = f"光学色彩补偿 {dens} 档（偏向{hue_names[hue]}色）"
        else:
            label, group, summary = f.name, "其他", ""
        entries.append((f.id, label, group, summary, idx))
    return entries


